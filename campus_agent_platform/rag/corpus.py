def seed_knowledge(db: Database) -> int:
    """把语料写入 knowledge_chunks（幂等：按 title 去重）。返回写入条数。"""
    inserted = 0
    for i, chunk in enumerate(KNOWLEDGE_CHUNKS):
        title = chunk["title"]
        exists = db.execute(
            "SELECT 1 FROM knowledge_chunks WHERE title=?", (title,)
        ).fetchone()
        if exists:
            continue
        db.execute(
            "INSERT INTO knowledge_chunks (chunk_id, category, title, content, keywords) "
            "VALUES (?,?,?,?,?)",
            (f"KC{i:03d}", chunk["category"], title, chunk["content"], chunk["keywords"]),
        )
        inserted += 1
    db.commit()
    return inserted
